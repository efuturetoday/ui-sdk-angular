// A token's variable: colors drop their group, and the base radius is `--ui-radius`.
function variable(token) {
  const name = token
    .replace(/^color\./, "")
    .replace(/^radius\.base$/, "radius")
    .replaceAll(".", "-")
  return `--ui-${name}`
}

// Every token in a file, by its path, with its type and value.
function flatten(group, type, prefix = []) {
  const found = new Map()
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$")) {
      continue
    }
    const at = [...prefix, key]
    const own = node.$type ?? type
    if ("$value" in node) {
      found.set(at.join("."), { type: own, value: node.$value })
    } else {
      for (const entry of flatten(node, own, at)) {
        found.set(...entry)
      }
    }
  }
  return found
}

const generic = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "ui-monospace",
  "system-ui",
])
const number = (n) => String(Math.round(n * 10000) / 10000)

// A token's value in CSS. A reference, like `{color.input}`, is its variable.
function css(type, value, tokens) {
  if (typeof value === "string" && /^\{.+\}$/.test(value)) {
    const token = value.slice(1, -1)
    if (!tokens.has(token)) {
      throw new Error(`No token ${token}`)
    }
    return `var(${variable(token)})`
  }
  switch (type) {
    case "color": {
      if ((value.alpha ?? 1) === 1) {
        return value.hex
      }
      const [r, g, b] = value.components.map((c) => Math.round(c * 255))
      return `rgb(${r} ${g} ${b} / ${number(value.alpha)})`
    }
    case "dimension":
    case "duration":
      return `${number(value.value)}${value.unit}`
    case "fontFamily":
      return [value]
        .flat()
        .map((name) =>
          generic.has(name) || !name.includes(" ") ? name : `"${name}"`
        )
        .join(", ")
    case "shadow":
      return [value]
        .flat()
        .map((layer) =>
          [
            layer.inset ? "inset" : "",
            css("dimension", layer.offsetX, tokens),
            css("dimension", layer.offsetY, tokens),
            css("dimension", layer.blur, tokens),
            css("dimension", layer.spread, tokens),
            css("color", layer.color, tokens),
          ]
            .filter(Boolean)
            .join(" ")
        )
        .join(", ")
    default:
      throw new Error(`No CSS for tokens of type ${type}`)
  }
}

// A theme's tokens.css: its tokens from base.json, light.json and dark.json,
// with `light-dark()` where the modes differ, then the values derived.json
// works out from them, so overriding a token's variable changes those too.
function tokensCss(dir) {
  const read = (name) =>
    JSON.parse(readFileSync(path.join(dir, `tokens/${name}.json`), "utf8"))
  const shared = flatten(read("base"))
  const lights = new Map([...flatten(read("light")), ...shared])
  const darks = new Map([...flatten(read("dark")), ...shared])
  const declarations = []
  for (const [token, { type, value }] of lights) {
    const other = darks.get(token)
    if (!other) {
      throw new Error(`${dir}: dark.json has no ${token}`)
    }
    const a = css(type, value, lights)
    const b = css(other.type, other.value, darks)
    declarations.push([variable(token), a === b ? a : `light-dark(${a}, ${b})`])
  }
  for (const token of darks.keys()) {
    if (!lights.has(token)) {
      throw new Error(`${dir}: light.json has no ${token}`)
    }
  }
  const derived = path.join(dir, "derived.json")
  if (existsSync(derived)) {
    declarations.push(
      ...Object.entries(JSON.parse(readFileSync(derived, "utf8")))
    )
  }
  // `data-ui-tokens` sets only the variables, for styles of an app's own.
  return `:where([data-ui-theme]),
:where([data-ui-tokens]),
:where([data-ui-theme], [data-ui-tokens]) [data-color-scheme] {
${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}
}

@media (prefers-reduced-motion: reduce) {
  :where([data-ui-theme]),
  :where([data-ui-tokens]) {
    --ui-duration: 0ms;
  }
}
`
}

// A theme's palettes, palettes/<name>, each with a light.json, a dark.json or
// both, and only colors.
function palettesOf(dir) {
  const found = path.join(dir, "palettes")
  return existsSync(found) ? readdirSync(found).sort() : []
}

const swatchTokens = [
  "color.background",
  "color.surface-3",
  "color.primary",
  "color.foreground",
]

// A palette's colors in place of the theme's, wherever `data-ui-palette`
// names it: on the theme's element or around it. One that has one mode only
// sets that color scheme too. Its few colors to show it by are `swatches`.
function paletteCss(dir, name) {
  const modes = ["light", "dark"].filter((mode) =>
    existsSync(path.join(dir, `palettes/${name}/${mode}.json`))
  )
  const [first, second] = modes.map(
    (mode) =>
      new Map(
        [
          ...flatten(
            JSON.parse(
              readFileSync(
                path.join(dir, `palettes/${name}/${mode}.json`),
                "utf8"
              )
            )
          ),
        ].filter(([token]) => token.startsWith("color."))
      )
  )
  const theme = flatten(
    JSON.parse(readFileSync(path.join(dir, "tokens/light.json"), "utf8"))
  )
  for (const token of theme.keys()) {
    if (
      token.startsWith("color.") &&
      (!first.has(token) || (second && !second.has(token)))
    ) {
      throw new Error(`${dir}: palette ${name} has no ${token}`)
    }
  }
  const declarations = [...first].map(([token, { type, value }]) => {
    const a = css(type, value, first)
    const other = second?.get(token)
    const b = other ? css(other.type, other.value, second) : a
    return `  ${variable(token)}: ${a === b ? a : `light-dark(${a}, ${b})`};`
  })
  const at = `[data-ui-palette="${name}"]`
  const scheme =
    modes.length === 1
      ? `\n\n:where(${at}) {\n  color-scheme: ${modes[0]};\n}\n`
      : "\n"
  return {
    scheme: modes.length === 1 ? modes[0] : null,
    swatches: swatchTokens
      .filter((token) => first.has(token))
      .map((token) => first.get(token).value.hex),
    css: `:where(${at}),
:where(${at} [data-ui-theme]),
:where(${at} [data-ui-tokens]),
:where(${at}) [data-color-scheme] {
${declarations.join("\n")}
}${scheme}`,
  }
}

// A selector list's parts at its top level, split at `,` or at combinators.
function split(selector, at) {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < selector.length; i++) {
    const char = selector[i]
    if ("([".includes(char)) {
      depth++
    } else if (")]".includes(char)) {
      depth--
    } else if (char === '"' || char === "'") {
      i = selector.indexOf(char, i + 1)
    } else if (!depth && at.test(char)) {
      parts.push(selector.slice(start, i))
      start = i + 1
    }
  }
  return [...parts, selector.slice(start)].map((part) => part.trim())
}

const list = (selector) => split(selector, /,/)

// A selector's compound selectors and the combinators between them, like
// `a > b c` as `a`, ` > `, `b`, ` `, `c`.
function compounds(selector) {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < selector.length; i++) {
    const char = selector[i]
    if ("([".includes(char)) {
      depth++
    } else if (")]".includes(char)) {
      depth--
    } else if (char === '"' || char === "'") {
      i = selector.indexOf(char, i + 1)
    } else if (!depth && /[\s>+~]/.test(char)) {
      let end = i
      while (/[\s>+~]/.test(selector[end] ?? "")) {
        end++
      }
      parts.push(selector.slice(start, i), selector.slice(i, end))
      start = end
      i = end - 1
    }
  }
  return [...parts, selector.slice(start)]
}

const functional = /:[a-z-]+\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)/g
const complex = (selector) => compounds(selector).length > 1

// A browser tries a rule whose subject has no tag, class, id or attribute,
// like `:is(button, a)`, on every element, and checks ancestors in a list
// slowly. So a list becomes a selector each, unless the subject has a key.
function keyed(selector) {
  const parts = compounds(selector)
  for (let i = 0; i < parts.length; i += 2) {
    const part = parts[i]
    const subject = i === parts.length - 1
    if (subject && /[[.#]|^[a-z]/.test(part.replace(functional, ""))) {
      continue
    }
    // Only a list of the compound's own, not one inside, like `:has(:is())`.
    let match = null
    for (let at = 0, depth = 0; at < part.length && !match; at++) {
      if (!depth && /^:(is|where)\(/.test(part.slice(at))) {
        match = /^:(is|where)\(/.exec(part.slice(at))
        match.index = at
      }
      depth += { "(": 1, ")": -1 }[part[at]] ?? 0
    }
    if (!match) {
      continue
    }
    const open = match.index + match[0].length
    let depth = 1
    let close = open
    while (depth) {
      depth += { "(": 1, ")": -1 }[part[close++]] ?? 0
    }
    const options = list(part.slice(open, close - 1))
    const before = part.slice(0, match.index)
    const after = part.slice(close)
    const lead = parts.slice(0, i).join("")
    const rest = parts.slice(i + 1).join("")
    // At the start, `:is(a b)` is `a b`.
    const inline = (option) =>
      match[1] === "is" && !i && !before && complex(option)
    if (options.length === 1 && !inline(options[0])) {
      continue
    }
    return options.flatMap((option) => {
      if (inline(option)) {
        return keyed(option + after + rest)
      }
      if (match[1] === "where" || complex(option)) {
        return keyed(`${lead}${before}:${match[1]}(${option})${after}${rest}`)
      }
      // A tag leads its compound selector.
      const tag = /^(?:[a-z][a-z0-9-]*|\*)/.exec(option)?.[0] ?? ""
      return keyed(
        lead + tag + before + option.slice(tag.length) + after + rest
      )
    })
  }
  return [selector]
}

// Nesting written out: `a, b { &:hover {} }` is `a:hover, b:hover`. A browser
// reads `&` as `:is(a, b)`, which has no key.
function unnest(nodes, parents) {
  const nested = (node) => node.type === "rule" || node.type === "atrule"
  return nodes.flatMap((node) => {
    if (node.type === "rule") {
      const selectors = parents
        ? node.selectors.flatMap((selector) =>
            parents.map((parent) =>
              // After a combinator, `&` keeps its own, as `x > &` matches
              // anything `&` does that's in an `x`.
              selector.startsWith("&") && !selector.slice(1).includes("&")
                ? parent + selector.slice(1)
                : selector.replaceAll(
                    "&",
                    split(parent, /[\s>+~]/).length > 1
                      ? `:is(${parent})`
                      : parent
                  )
            )
          )
        : node.selectors
      const own = node.clone({ nodes: [] })
      own.selectors = [...new Set(selectors.flatMap(keyed))]
      own.append(
        node.nodes
          .filter((child) => !nested(child))
          .map((child) => child.clone())
      )
      return [
        ...(own.nodes.some((child) => child.type === "decl") ? [own] : []),
        ...unnest(node.nodes.filter(nested), selectors),
      ]
    }
    if (node.type === "atrule" && node.nodes) {
      const own = node.clone({ nodes: [] })
      const decls = node.nodes.filter((child) => child.type === "decl")
      if (parents && decls.length) {
        own.append(
          postcss.rule({
            selectors: [...new Set(parents.flatMap(keyed))],
            nodes: decls.map((decl) => decl.clone()),
          })
        )
      }
      own.append(
        unnest(
          node.nodes.filter((child) => child.type !== "decl"),
          parents
        )
      )
      return own.nodes.length ? [own] : []
    }
    return [node.clone()]
  })
}

// A stylesheet with its nesting written out.
function written(css) {
  const ast = postcss.parse(css)
  ast.append(unnest(ast.nodes.splice(0), null))
  return ast.toString().trim()
}

const problems = []

// Every part @ui-sdk/core renders, like `dialog-content`: each primitive's
// slots, and the ones the adapter adds, like a list's `item-icon`.
const primitives = new Map()
const coreParts = new Set()
const pkg = JSON.parse(
  readFileSync(
    path.join(root, "node_modules/@ui-sdk/core/package.json"),
    "utf8"
  )
)
for (const entry of Object.keys(pkg.exports)) {
  if (/\.(css|json)$|testing|renderer|\*/.test(entry)) {
    continue
  }
  const exported = await import(`@ui-sdk/core${entry.slice(1)}`)
  for (const [name, value] of Object.entries(exported)) {
    if (typeof value === "function" && value.slots && value.name) {
      primitives.set(name, value.name)
      for (const slot of Object.keys(value.slots)) {
        coreParts.add(slot === "root" ? value.name : `${value.name}-${slot}`)
      }
    }
  }
}
const parts = new Set(coreParts)
const adapter = path.join(root, "projects/core")
for (const dir of readdirSync(adapter)) {
  const file = path.join(adapter, dir, `src/${dir}.ts`)
  if (!existsSync(file)) {
    continue
  }
  const source = readFileSync(file, "utf8")
  const used = [...primitives].filter(([name]) =>
    new RegExp(`\\b${name}\\b`).test(source)
  )
  for (const [, slot] of source.matchAll(/"([a-z]+(?:-[a-z]+)*)"/g)) {
    for (const [, name] of used) {
      parts.add(`${name}-${slot}`)
    }
  }
}

// The slots a stylesheet names exactly, leaving out those it excludes, like
// `:not([data-slot="row"])`.
const slotsIn = (css) =>
  [
    ...css
      .replace(/:not\((?:[^()]|\([^()]*\))*\)/g, "")
      .matchAll(/\[data-slot="([^"]+)"\]/g),
  ].map(([, slot]) => slot)

const sources = readdirSync(styles)
  .filter((file) => file.endsWith(".css"))
  .map((file) => file.slice(0, -4))
  .sort((a, b) => (a === "base" ? -1 : b === "base" ? 1 : a.localeCompare(b)))
const shared = new Map(
  sources.map((source) => [
    source,
    readFileSync(path.join(styles, `${source}.css`), "utf8"),
  ])
)

// A theme styles parts, plain elements and the slots the docs' examples write,
// like `stack`, so a copied example looks as it does in the docs.
const examples = path.join(root, "projects/docs/src/examples")
const exampleSlots = new Set()
for (const dir of readdirSync(examples, { withFileTypes: true })) {
  if (!dir.isDirectory()) {
    continue
  }
  for (const file of readdirSync(path.join(examples, dir.name))) {
    const source = readFileSync(path.join(examples, dir.name, file), "utf8")
    for (const [, slot] of source.matchAll(/data-slot="([^"]+)"/g)) {
      exampleSlots.add(slot)
    }
  }
}
for (const [source, css] of shared) {
  for (const slot of new Set(slotsIn(css))) {
    if (!parts.has(slot) && !exampleSlots.has(slot)) {
      problems.push(
        `projects/themes/styles/${source}.css styles ${slot}, which is no part and no example writes`
      )
    }
  }
}

// Upstream's example styles and core's parts as last reviewed. A change to
// either fails until it's ported to the styles and recorded with `--lock`.
const hash = (file) =>
  createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 16)
const upstream = {
  styles: Object.fromEntries(
    [
      "styles/base.css",
      ...readdirSync(path.join(vendor, "components"))
        .filter((name) =>
          existsSync(path.join(vendor, `components/${name}/${name}.css`))
        )
        .sort()
        .map((name) => `components/${name}/${name}.css`),
    ].map((file) => [file, hash(path.join(vendor, file))])
  ),
  parts: [...coreParts].sort(),
}
if (lock) {
  writeFileSync(lockFile, JSON.stringify(upstream, null, 2) + "\n")
} else {
  const reviewed = JSON.parse(readFileSync(lockFile, "utf8"))
  const changed = Object.keys(upstream.styles).filter(
    (file) => reviewed.styles[file] !== upstream.styles[file]
  )
  if (changed.length) {
    problems.push(
      `Upstream's styles changed: ${changed.join(", ")}. See git -C vendor/ui diff <last tag> -- ${changed.map((file) => `examples/${file}`).join(" ")}, port what applies to projects/themes/styles, then run node scripts/build-theme.mjs --lock`
    )
  }
  const added = upstream.parts.filter((part) => !reviewed.parts.includes(part))
  if (added.length) {
    problems.push(
      `@ui-sdk/core has new parts: ${added.join(", ")}. Style them in projects/themes/styles if they need it, then run node scripts/build-theme.mjs --lock`
    )
  }
}

const files = new Map()
// Each theme's palettes as the docs' picker shows them, its own colors first.
const shownPalettes = {}
for (const name of readdirSync(themes).sort()) {
  const dir = path.join(themes, name)
  if (!existsSync(path.join(dir, "tokens"))) {
    continue
  }
  const tokens = tokensCss(dir)
  const declared = new Set(
    [...tokens.matchAll(/^\s+(--ui-[a-z0-9-]+):/gm)].map(([, found]) => found)
  )
  const overrides = new Map(
    sources
      .filter((source) => existsSync(path.join(dir, `overrides/${source}.css`)))
      .map((source) => [
        source,
        readFileSync(path.join(dir, `overrides/${source}.css`), "utf8"),
      ])
  )
  // Every variable the styles read is one of the theme's tokens.
  for (const css of [...shared.values(), ...overrides.values()]) {
    for (const [, found] of css.matchAll(/var\((--ui-[a-z0-9-]+)/g)) {
      if (!declared.has(found)) {
        declared.add(found)
        problems.push(`projects/themes/${name} has no ${found}`)
      }
    }
  }
  files.set(`projects/themes/${name}/src/tokens.css`, header + tokens)
  const theme = flatten(
    JSON.parse(readFileSync(path.join(dir, "tokens/light.json"), "utf8"))
  )
  const palettes = [
    {
      name: null,
      scheme: null,
      swatches: swatchTokens
        .filter((token) => theme.has(token))
        .map((token) => theme.get(token).value.hex),
    },
  ]
  for (const palette of palettesOf(dir)) {
    const { css: paletteStyles, ...shown } = paletteCss(dir, palette)
    files.set(
      `projects/themes/${name}/src/palettes/${palette}.css`,
      header + paletteStyles
    )
    palettes.push({ name: palette, ...shown })
  }
  shownPalettes[name] = palettes
  // A theme's overrides/<source>.css, for a shape its tokens can't give, like
  // Material's round buttons, comes after the shared styles.
  for (const [source, css] of shared) {
    files.set(
      `projects/themes/${name}/src/${source}.css`,
      header +
        [css, overrides.get(source)].filter(Boolean).map(written).join("\n\n") +
        "\n"
    )
  }
  files.set(
    `projects/themes/${name}/src/all.css`,
    header +
      ["tokens", ...sources]
        .map((source) => `@import "./${source}.css";`)
        .join("\n") +
      "\n"
  )
  // The docs show each component as the theme draws it, then the demo's
  // layout of its examples.
  files.set(
    `projects/docs/src/themes/${name}.css`,
    header +
      [
        `@import "../../../themes/${name}/src/tokens.css";`,
        ...palettesOf(dir).map(
          (palette) =>
            `@import "../../../themes/${name}/src/palettes/${palette}.css";`
        ),
        ...sources.flatMap((source) => [
          `@import "../../../themes/${name}/src/${source}.css";`,
          ...(existsSync(path.join(demo, `${source}.css`))
            ? [`@import "../demo/${source}.css";`]
            : []),
        ]),
      ].join("\n") +
      "\n"
  )
}
files.set(
  "projects/docs/src/themes/palettes.ts",
  `// Generated by \`node scripts/build-theme.mjs\`.
type Palette = {
  name: string | null
  scheme: "light" | "dark" | null
  swatches: string[]
}

const palettes: Record<string, Palette[]> = ${JSON.stringify(shownPalettes, null, 2)}

export { type Palette, palettes }
`
)

const stale = []
for (const [file, content] of files) {
  const target = path.join(root, file)
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
      stale.push(file)
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, content)
  }
}
if (stale.length) {
  problems.push(
    `Out of date (${stale.join(", ")}): run node scripts/build-theme.mjs`
  )
}
for (const problem of problems) {
  console.error(problem)
}
if (problems.length) {
  process.exitCode = 1
}
