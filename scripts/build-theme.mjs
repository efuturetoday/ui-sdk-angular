// Writes @ngx-ui-sdk/theme-default's stylesheets from vendor/ui/examples,
// scoped to `[data-ui-theme]` and without rules for single examples; `--check`
// fails when they're out of date. See projects/themes/default/README.md.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import postcss from "postcss"

const root = path.resolve(import.meta.dirname, "..")
const vendor = path.join(root, "vendor/ui/examples")
const out = path.join(root, "projects/themes/default/src")
const check = process.argv.includes("--check")
const header =
  "/* Generated by `node scripts/build-theme.mjs` from ui-sdk's example styles. */\n"

// A selector for one example, like `:scope[data-example="accordion/search"]`.
const oneExample = /\[data-example\s*[\^$*]?=/

function theme(css) {
  const ast = postcss.parse(css)
  ast.walkAtRules("scope", (rule) => {
    rule.params = rule.params.replace("[data-example]", "[data-ui-theme]")
  })
  ast.walkRules((rule) => {
    if (!oneExample.test(rule.selector)) {
      return
    }
    const kept = rule.selectors.filter((selector) => !oneExample.test(selector))
    if (kept.length) {
      rule.selectors = kept
    } else {
      rule.remove()
    }
  })
  // Leave no empty blocks behind the removed rules.
  ast.walkAtRules((rule) => {
    if (rule.nodes && !rule.nodes.length) {
      rule.remove()
    }
  })
  return ast.toString()
}

const files = new Map()
for (const name of ["tokens", "base"]) {
  files.set(
    `${name}.css`,
    theme(readFileSync(path.join(vendor, `styles/${name}.css`), "utf8"))
  )
}
const components = readdirSync(path.join(vendor, "components"))
  .filter((name) =>
    existsSync(path.join(vendor, `components/${name}/${name}.css`))
  )
  .sort()
for (const name of components) {
  files.set(
    `${name}.css`,
    theme(
      readFileSync(path.join(vendor, `components/${name}/${name}.css`), "utf8")
    )
  )
}
files.set(
  "all.css",
  ["tokens", "base", ...components]
    .map((name) => `@import "./${name}.css";`)
    .join("\n") + "\n"
)

const stale = []
for (const [file, css] of files) {
  const target = path.join(out, file)
  const content = header + css
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
      stale.push(file)
    }
  } else {
    writeFileSync(target, content)
  }
}
if (stale.length) {
  console.error(
    `projects/themes/default/src is out of date (${stale.join(", ")}): run node scripts/build-theme.mjs`
  )
  process.exitCode = 1
}
