// Upstream draws text, strong borders and fills all with `--ink`, and the
// text on those fills with `--paper`. A theme sets each role on its own, so
// which one a use is depends on the property it's in.
const fills = /^(background(-color)?|accent-color)$/
const borders = /^(box-shadow|border(-[a-z-]+)?|outline(-color)?)$/
function roleOf(name, prop) {
  if (name === "ink" && fills.test(prop)) {
    return "--ui-primary"
  }
  if (name === "ink" && borders.test(prop)) {
    return "--ui-border-strong"
  }
  if (name === "paper" && prop === "color") {
    return "--ui-primary-foreground"
  }
  return renames[name]
}

// Upstream's variables in a declaration, like `var(--ink)`, become the theme's.
function rename(prop, value) {
  return value.replace(/var\(--([a-z0-9-]+)(?=[,)\s])/g, (whole, name) =>
    renames[name] ? `var(${roleOf(name, prop)}` : whole
  )
}

// A token's variable: colors drop their group, and the base radius is `--ui-radius`.
function variable(token) {
  const name = token
    .replace(/^color\./, "")
    .replace(/^radius\.base$/, "radius")
    .replaceAll(".", "-")
  return `--ui-${name}`
}

// Every token in a file, by its path, with its type and value.
function flatten(group, type, prefix = []) {
  const found = new Map()
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$")) {
      continue
    }
    const at = [...prefix, key]
    const own = node.$type ?? type
    if ("$value" in node) {
      found.set(at.join("."), { type: own, value: node.$value })
    } else {
      for (const entry of flatten(node, own, at)) {
        found.set(...entry)
      }
    }
  }
  return found
}

const generic = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "ui-monospace",
  "system-ui",
])
const number = (n) => String(Math.round(n * 10000) / 10000)

// A token's value in CSS. A reference, like `{color.input}`, is its variable.
function css(type, value, tokens) {
  if (typeof value === "string" && /^\{.+\}$/.test(value)) {
    const token = value.slice(1, -1)
    if (!tokens.has(token)) {
      throw new Error(`No token ${token}`)
    }
    return `var(${variable(token)})`
  }
  switch (type) {
    case "color": {
      if ((value.alpha ?? 1) === 1) {
        return value.hex
      }
      const [r, g, b] = value.components.map((c) => Math.round(c * 255))
      return `rgb(${r} ${g} ${b} / ${number(value.alpha)})`
    }
    case "dimension":
    case "duration":
      return `${number(value.value)}${value.unit}`
    case "fontFamily":
      return [value]
        .flat()
        .map((name) =>
          generic.has(name) || !name.includes(" ") ? name : `"${name}"`
        )
        .join(", ")
    case "shadow":
      return [value]
        .flat()
        .map((layer) =>
          [
            layer.inset ? "inset" : "",
            css("dimension", layer.offsetX, tokens),
            css("dimension", layer.offsetY, tokens),
            css("dimension", layer.blur, tokens),
            css("dimension", layer.spread, tokens),
            css("color", layer.color, tokens),
          ]
            .filter(Boolean)
            .join(" ")
        )
        .join(", ")
    default:
      throw new Error(`No CSS for tokens of type ${type}`)
  }
}

// A theme's tokens.css: its tokens from base.json, light.json and dark.json,
// with `light-dark()` where the modes differ, then the values derived.json
// works out from them, so overriding a token's variable changes those too.
function tokensCss(dir) {
  const read = (name) =>
    JSON.parse(readFileSync(path.join(dir, `tokens/${name}.json`), "utf8"))
  const shared = flatten(read("base"))
  const lights = new Map([...flatten(read("light")), ...shared])
  const darks = new Map([...flatten(read("dark")), ...shared])
  const declarations = []
  for (const [token, { type, value }] of lights) {
    const other = darks.get(token)
    if (!other) {
      throw new Error(`${dir}: dark.json has no ${token}`)
    }
    const a = css(type, value, lights)
    const b = css(other.type, other.value, darks)
    declarations.push([variable(token), a === b ? a : `light-dark(${a}, ${b})`])
  }
  for (const token of darks.keys()) {
    if (!lights.has(token)) {
      throw new Error(`${dir}: light.json has no ${token}`)
    }
  }
  const derived = path.join(dir, "derived.json")
  if (existsSync(derived)) {
    declarations.push(
      ...Object.entries(JSON.parse(readFileSync(derived, "utf8")))
    )
  }
  // `data-ui-tokens` sets only the variables, for styles of an app's own.
  return `:where([data-ui-theme]),
:where([data-ui-tokens]),
:where([data-ui-theme], [data-ui-tokens]) [data-color-scheme] {
${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}
}

@media (prefers-reduced-motion: reduce) {
  :where([data-ui-theme]),
  :where([data-ui-tokens]) {
    --ui-duration: 0ms;
  }
}
`
}

// A theme's palettes, palettes/<name>, each with a light.json, a dark.json or
// both, and only colors.
function palettesOf(dir) {
  const found = path.join(dir, "palettes")
  return existsSync(found) ? readdirSync(found).sort() : []
}

